-- Kobel database schema (Cloudflare D1 / SQLite).
-- Apply with:  npx wrangler d1 migrations apply kobel-db --remote   (see docs/DEPLOYMENT.md)
--
-- Design notes
--  * One user owns many cards and rules, and has exactly one profile row.
--  * "updated_at" is the client's clock (milliseconds); the newest edit wins ("last write wins").
--  * "synced_at" is the server's clock; devices ask for rows with synced_at greater than their cursor.
--  * Deleted rows are kept as tombstones (deleted = 1) so other devices learn about the deletion.
--  * Foreign keys cascade, so deleting a user removes all of their data.

CREATE TABLE users (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  name       TEXT    NOT NULL CHECK (length(name) BETWEEN 1 AND 40),
  token_hash TEXT    NOT NULL UNIQUE,            -- SHA-256 (hex) of the access code; the code itself is never stored
  created_at INTEGER NOT NULL
);

CREATE TABLE cards (
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  id          TEXT    NOT NULL,                  -- stable id generated by the app (same word = same id on every device)
  type        TEXT    NOT NULL CHECK (type IN ('w','g')),   -- w = vocabulary word/phrase, g = grammar gap sentence
  lesson      TEXT    NOT NULL DEFAULT '',
  lesson_date TEXT    NOT NULL DEFAULT '',       -- YYYY-MM-DD of the class
  de          TEXT    NOT NULL DEFAULT '',
  art         TEXT    NOT NULL DEFAULT '' CHECK (art IN ('','der','die','das')),
  pl          TEXT    NOT NULL DEFAULT '',
  forms       TEXT    NOT NULL DEFAULT '',
  en          TEXT    NOT NULL DEFAULT '',
  ex          TEXT    NOT NULL DEFAULT '',
  ex_en       TEXT    NOT NULL DEFAULT '',
  note        TEXT    NOT NULL DEFAULT '',
  sentence    TEXT    NOT NULL DEFAULT '',
  topic       TEXT    NOT NULL DEFAULT '',
  hint        TEXT    NOT NULL DEFAULT '',
  created_at  INTEGER NOT NULL DEFAULT 0,
  due         INTEGER NOT NULL DEFAULT 0,        -- spaced-repetition progress from here on
  iv          INTEGER NOT NULL DEFAULT 0,
  ease        REAL    NOT NULL DEFAULT 2.5,
  reps        INTEGER NOT NULL DEFAULT 0,
  lapses      INTEGER NOT NULL DEFAULT 0,
  seen        INTEGER NOT NULL DEFAULT 0,
  ok          INTEGER NOT NULL DEFAULT 0,
  bad         INTEGER NOT NULL DEFAULT 0,
  susp        INTEGER NOT NULL DEFAULT 0 CHECK (susp IN (0,1)),
  bury        INTEGER NOT NULL DEFAULT 0,
  updated_at  INTEGER NOT NULL,
  synced_at   INTEGER NOT NULL,
  deleted     INTEGER NOT NULL DEFAULT 0 CHECK (deleted IN (0,1)),
  PRIMARY KEY (user_id, id)
);
CREATE INDEX idx_cards_sync ON cards (user_id, synced_at);

CREATE TABLE rules (
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  id         TEXT    NOT NULL,
  topic      TEXT    NOT NULL DEFAULT '',
  lesson     TEXT    NOT NULL DEFAULT '',
  text       TEXT    NOT NULL DEFAULT '',
  updated_at INTEGER NOT NULL,
  synced_at  INTEGER NOT NULL,
  deleted    INTEGER NOT NULL DEFAULT 0 CHECK (deleted IN (0,1)),
  PRIMARY KEY (user_id, id)
);
CREATE INDEX idx_rules_sync ON rules (user_id, synced_at);

-- XP, streak, badges, minigame records and settings: one small JSON document per user.
CREATE TABLE profiles (
  user_id    INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  data       TEXT    NOT NULL,                   -- JSON: { stats, games, settings }
  updated_at INTEGER NOT NULL,
  synced_at  INTEGER NOT NULL
);

-- 0002: notification inbox and unique usernames (see database/migrations/0002_notices.sql)
CREATE TABLE notices (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  kind       TEXT    NOT NULL DEFAULT 'news' CHECK (kind IN ('news', 'update', 'tip')),
  title      TEXT    NOT NULL CHECK (length(title) BETWEEN 1 AND 80),
  body       TEXT    NOT NULL DEFAULT '' CHECK (length(body) <= 1000),
  created_at INTEGER NOT NULL
);
CREATE INDEX idx_notices_created ON notices (created_at DESC);
CREATE UNIQUE INDEX idx_users_name_nocase ON users (name COLLATE NOCASE);

-- 0003: anonymous accounts (see database/migrations/0003_accounts.sql)
ALTER TABLE users ADD COLUMN visible INTEGER NOT NULL DEFAULT 1 CHECK (visible IN (0, 1));
CREATE TABLE signups (
  bucket TEXT    NOT NULL,
  day    TEXT    NOT NULL,
  n      INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (bucket, day)
);

-- 0004: friends and duels (see database/migrations/0004_friends_duels.sql for the commented version)
CREATE TABLE friend_codes (
  user_id    INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  code       TEXT    NOT NULL UNIQUE,
  created_at INTEGER NOT NULL
);
CREATE TABLE friends (
  user_a     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_b     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at INTEGER NOT NULL,
  added_by   INTEGER,
  PRIMARY KEY (user_a, user_b),
  CHECK (user_a < user_b)
);
CREATE INDEX idx_friends_b ON friends (user_b);
CREATE TABLE duels (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  game       TEXT    NOT NULL CHECK (game IN ('sprint', 'dash', 'plural', 'gap', 'scramble')),
  mode       TEXT    NOT NULL CHECK (mode IN ('live', 'turn')),
  a_user     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  b_user     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status     TEXT    NOT NULL DEFAULT 'invited' CHECK (status IN ('invited', 'active', 'done', 'declined', 'expired')),
  deck       TEXT    NOT NULL,
  a_answers  TEXT    NOT NULL DEFAULT '[]',
  b_answers  TEXT    NOT NULL DEFAULT '[]',
  a_score    INTEGER NOT NULL DEFAULT 0,
  b_score    INTEGER NOT NULL DEFAULT 0,
  a_done     INTEGER NOT NULL DEFAULT 0 CHECK (a_done IN (0, 1)),
  b_done     INTEGER NOT NULL DEFAULT 0 CHECK (b_done IN (0, 1)),
  a_t        INTEGER NOT NULL DEFAULT 0,
  b_t        INTEGER NOT NULL DEFAULT 0,
  start_at   INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  finished_by INTEGER,
  CHECK (a_user <> b_user)
);
CREATE INDEX idx_duels_a ON duels (a_user, updated_at DESC);
CREATE INDEX idx_duels_b ON duels (b_user, updated_at DESC);

-- 0005: study groups
CREATE TABLE groups (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  name       TEXT    NOT NULL,
  owner      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL
);

CREATE TABLE group_members (
  group_id  INTEGER NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
  user_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  added_by  INTEGER,
  joined_at INTEGER NOT NULL,
  PRIMARY KEY (group_id, user_id)
);
CREATE INDEX idx_group_members_user ON group_members (user_id, joined_at DESC);

CREATE TABLE group_games (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  group_id   INTEGER NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
  game       TEXT    NOT NULL CHECK (game IN ('sprint', 'dash', 'plural', 'gap', 'scramble')),
  creator    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  deck       TEXT    NOT NULL,                                  -- JSON: questions and right answers (never sent to players)
  status     TEXT    NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'done')),
  created_at INTEGER NOT NULL,
  expires_at INTEGER NOT NULL,
  settled_at INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_group_games_group ON group_games (group_id, created_at DESC);

CREATE TABLE group_plays (
  game_id     INTEGER NOT NULL REFERENCES group_games(id) ON DELETE CASCADE,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  answers     TEXT    NOT NULL DEFAULT '[]',
  score       INTEGER NOT NULL DEFAULT 0,                       -- goals: right answers, 0 to 9
  done        INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0, 1)),
  t           INTEGER NOT NULL DEFAULT 0,                       -- server time the current question was handed out
  finished_at INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (game_id, user_id)
);
CREATE INDEX idx_group_plays_user ON group_plays (user_id, finished_at DESC);
